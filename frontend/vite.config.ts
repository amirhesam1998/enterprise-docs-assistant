import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";

export default defineConfig({
  plugins: [react(), tailwindcss()],
  server: {
    port: 5173,
    // Backend runs on 127.0.0.1:8000. We hit it directly (CORS is configured
    // there for http://localhost:5173), so no proxy is strictly needed, but a
    // proxy keeps the origin identical and avoids any preflight surprises.
    proxy: {
      "/api": {
        target: "http://127.0.0.1:8000",
        changeOrigin: true,
        rewrite: (p) => p.replace(/^\/api/, ""),
      },
    },
  },
});
